import 'package:farmerconnect/service/location_services.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:geolocator/geolocator.dart';
import 'package:mockito/annotations.dart';
import 'package:mockito/mockito.dart';

// Generate mocks for GeolocatorPlatform
// Use the following command in the terminal:
// flutter pub run build_runner build --delete-conflicting-outputs
@GenerateMocks([GeolocatorPlatform])
import 'location_service_test.mocks.dart'; // Generated by Mockito

void main() {
  late LocationService locationService;
  late MockGeolocatorPlatform mockGeolocatorPlatform;

  setUp(() {
    mockGeolocatorPlatform = MockGeolocatorPlatform();
    // Crucial step: Override the GeolocatorPlatform.instance with the mock
    GeolocatorPlatform.instance = mockGeolocatorPlatform;
    locationService = LocationService();
  });

  group('LocationService getCurrentLocation', () {
    final mockPosition = Position(
      latitude: 37.7749,
      longitude: -122.4194,
      timestamp: DateTime.now(),
      accuracy: 0.0,
      altitude: 0.0,
      altitudeAccuracy: 0.0,
      heading: 0.0,
      headingAccuracy: 0.0,
      speed: 0.0,
      speedAccuracy: 0.0,
    );

    test('returns Position on successful location retrieval', () async {
      when(mockGeolocatorPlatform.isLocationServiceEnabled())
          .thenAnswer((_) async => true);
      when(mockGeolocatorPlatform.checkPermission())
          .thenAnswer((_) async => LocationPermission.whileInUse);
      when(mockGeolocatorPlatform.getCurrentPosition(
        locationSettings: anyNamed('locationSettings'),
      )).thenAnswer((_) async => mockPosition);

      final position = await locationService.getCurrentLocation();

      expect(position, equals(mockPosition));
      verify(mockGeolocatorPlatform.isLocationServiceEnabled()).called(1);
      verify(mockGeolocatorPlatform.checkPermission()).called(1);
      verify(mockGeolocatorPlatform.getCurrentPosition(locationSettings: anyNamed('locationSettings'))).called(1);
    });

    test('throws "Location services are disabled." if service is disabled', () async {
      when(mockGeolocatorPlatform.isLocationServiceEnabled())
          .thenAnswer((_) async => false);

      expect(
        locationService.getCurrentLocation(),
        throwsA(isA<Exception>().having(
          (e) => e.toString(),
          'message',
          'Exception: Location services are disabled.',
        )),
      );
      verify(mockGeolocatorPlatform.isLocationServiceEnabled()).called(1);
      verifyNever(mockGeolocatorPlatform.checkPermission());
    });

    test('requests permission if denied, then succeeds if granted', () async {
      when(mockGeolocatorPlatform.isLocationServiceEnabled()).thenAnswer((_) async => true);
      // First call to checkPermission returns denied
      when(mockGeolocatorPlatform.checkPermission()).thenAnswer((_) async => LocationPermission.denied);
      // Call to requestPermission returns whileInUse
      when(mockGeolocatorPlatform.requestPermission()).thenAnswer((_) async => LocationPermission.whileInUse);
      when(mockGeolocatorPlatform.getCurrentPosition(locationSettings: anyNamed('locationSettings')))
          .thenAnswer((_) async => mockPosition);

      final position = await locationService.getCurrentLocation();
      expect(position, equals(mockPosition));

      verify(mockGeolocatorPlatform.isLocationServiceEnabled()).called(1);
      verify(mockGeolocatorPlatform.checkPermission()).called(1); // Initial check
      verify(mockGeolocatorPlatform.requestPermission()).called(1); // Permission request
      verify(mockGeolocatorPlatform.getCurrentPosition(locationSettings: anyNamed('locationSettings'))).called(1);
    });
    
    test('throws "Location permissions are denied" if permission is denied after request', () async {
      when(mockGeolocatorPlatform.isLocationServiceEnabled()).thenAnswer((_) async => true);
      when(mockGeolocatorPlatform.checkPermission()).thenAnswer((_) async => LocationPermission.denied);
      when(mockGeolocatorPlatform.requestPermission()).thenAnswer((_) async => LocationPermission.denied);

      expect(
        locationService.getCurrentLocation(),
        throwsA(isA<Exception>().having(
          (e) => e.toString(),
          'message',
          'Exception: Location permissions are denied',
        )),
      );
      verify(mockGeolocatorPlatform.requestPermission()).called(1);
    });

    test('throws "Location permissions are permanently denied" if permission is deniedForever', () async {
      when(mockGeolocatorPlatform.isLocationServiceEnabled()).thenAnswer((_) async => true);
      // Scenario 1: checkPermission immediately returns deniedForever
      when(mockGeolocatorPlatform.checkPermission()).thenAnswer((_) async => LocationPermission.deniedForever);
      
      expect(
        locationService.getCurrentLocation(),
        throwsA(isA<Exception>().having(
          (e) => e.toString(),
          'message',
          'Exception: Location permissions are permanently denied, we cannot request permissions.',
        )),
      );
       verifyNever(mockGeolocatorPlatform.requestPermission()); // Should not request if already deniedForever

      // Scenario 2: checkPermission returns denied, then requestPermission returns deniedForever
      clearInteractions(mockGeolocatorPlatform); // Clear previous interactions for a clean test
      when(mockGeolocatorPlatform.isLocationServiceEnabled()).thenAnswer((_) async => true);
      when(mockGeolocatorPlatform.checkPermission()).thenAnswer((_) async => LocationPermission.denied);
      when(mockGeolocatorPlatform.requestPermission()).thenAnswer((_) async => LocationPermission.deniedForever);

       expect(
        locationService.getCurrentLocation(),
        throwsA(isA<Exception>().having(
          (e) => e.toString(),
          'message',
          'Exception: Location permissions are permanently denied, we cannot request permissions.',
        )),
      );
      verify(mockGeolocatorPlatform.requestPermission()).called(1);
    });

    test('handles LocationPermission.unableToDetermine gracefully', () async {
       when(mockGeolocatorPlatform.isLocationServiceEnabled()).thenAnswer((_) async => true);
      when(mockGeolocatorPlatform.checkPermission()).thenAnswer((_) async => LocationPermission.unableToDetermine);
      // If checkPermission returns unableToDetermine, the service might try to request permission
      // or handle it as a denied case. Let's assume it tries to request.
      when(mockGeolocatorPlatform.requestPermission()).thenAnswer((_) async => LocationPermission.unableToDetermine);

       expect(
        locationService.getCurrentLocation(),
        throwsA(isA<Exception>().having(
          (e) => e.toString(),
          'message',
          // Based on current LocationService, unableToDetermine is treated like denied.
          'Exception: Location permissions are denied', 
        )),
      );
    });
  });
}

